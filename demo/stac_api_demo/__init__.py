"""Launch the STAC adapter with the demo's registered GeoParquet service."""

import argparse

import uvicorn


def main() -> None:
    """Run Uvicorn, accepting an optional bind address and port."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=8000)
    arguments = parser.parse_args()
    uvicorn.run("stac_api_protocol.main:app", host=arguments.host, port=arguments.port)
